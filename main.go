// Muse tools stripper — CLIProxyAPI request interceptor + normalizer.
//
// Problem: codex clients (0.15x) send {"type":"additional_tools", ...} as
// input[0] (exec sandbox tool declarations). The opencode zen free tier
// (muse-spark-1.3-contributor-free, alias muse-free / muse) does not accept
// this type and rejects the whole request with:
//
//	400 [invalid_request_error] `input[0]` did not match any supported type
//
// Verified live: same payload without the additional_tools entry returns 200.
//
// Fix: for zen free-tier models only, drop input[] entries whose type is
// additional_tools. Two hooks cover both request shapes:
//   - request.intercept_before/after: strips when the client payload already
//     carries input[] (translation has nothing to generate yet).
//   - request.normalize: strips after native translation, covering requests
//     whose input[] is only generated by the provider translator.
//
// Standard entries (message / function_call / function_call_output /
// reasoning / custom tool calls) pass through untouched. exec sandbox is
// unavailable behind this filter; conversation, file edits and shell calls
// are unaffected.
package main

